    def test_backup_is_private_and_second_apply_is_noop(self) -> None:
        target = write_json(self.home / ".copilot/settings.json", {"askUser": False, "token": "private"})
        before = target.read_bytes()
        self.run_retire("--apply")
        base = self.home / ".local/state/agents-control-plane/retired-client-backups"
        backups = list(base.rglob("settings.json"))
        self.assertEqual(len(backups), 1)
        self.assertEqual(backups[0].read_bytes(), before)
        self.assertEqual(stat.S_IMODE(backups[0].stat().st_mode), 0o600)
        self.assertEqual(stat.S_IMODE(base.stat().st_mode), 0o700)
        before_files = sorted(str(path) for path in base.rglob("*"))
        self.assertIn("0 retired-client", self.run_retire("--apply").stdout)
        self.assertEqual(sorted(str(path) for path in base.rglob("*")), before_files)
        self.assertEqual(self.run_retire("--check").returncode, 0)

    def make_job(self, suffix: str, script: str | None = None, label_prefix: str = "com.fixture") -> Path:
        label = f"{label_prefix}.{suffix}"
        path = self.home / "Library/LaunchAgents" / f"{label}.plist"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(plistlib.dumps({"Label": label, "ProgramArguments": [script or str(self.github / "agents" / RETIRE.JOBS[suffix]), "--apply"]}))
        return path

    def test_fixture_jobs_are_removed_without_launchctl_and_unknown_job_is_preserved(self) -> None:
        owned = [self.make_job(suffix) for suffix in RETIRE.JOBS]
        unknown = self.make_job("claude-session-archiver", "/somewhere/custom-archiver.py", "com.other")
        migration = self.retirement()
        with mock.patch.object(RETIRE.subprocess, "run") as process:
            migration.plan()
            migration.apply()
        process.assert_not_called()
        self.assertTrue(unknown.exists())
        for path in owned:
            self.assertFalse(path.exists())
        self.assertEqual(len(list(migration.backup_dir.rglob("*.plist"))), 3)

    def test_live_job_unload_failure_keeps_plist_and_backup(self) -> None:
        job = self.make_job("copilot-session-pruner")
        migration = self.retirement()
        migration.plan()
        with mock.patch.object(RETIRE.pwd, "getpwuid", return_value=SimpleNamespace(pw_dir=str(self.home))), mock.patch.object(RETIRE.sys, "platform", "darwin"), mock.patch.object(RETIRE.subprocess, "run", side_effect=[subprocess.CompletedProcess([], 0, "loaded", ""), subprocess.CompletedProcess([], 1, "", "failed")]) as process:
            with self.assertRaisesRegex(RuntimeError, "Cannot unload"):
                migration.apply()
        self.assertEqual(process.call_count, 2)
        self.assertTrue(job.exists())
        self.assertEqual(len(list(migration.backup_dir.rglob("*.plist"))), 1)

