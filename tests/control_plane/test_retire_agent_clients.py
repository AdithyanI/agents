class RetireAgentClientsTests(TempDirTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.home = (self.temp_path / "home").resolve()
        self.github = self.home / "GitHub"
        self.repo = init_git_repo(self.github / "angie")
        self.other = init_git_repo(self.github / "other")
        self.registry = write_json(self.home / "repos.json", {"repos": [
            {"path": "~/GitHub/angie", "model_instructions_file": "../identity.md"},
            {"path": "~/GitHub/other"},
        ]})
        self.entries = [
            {"root": self.repo, "model_instructions_file": "../identity.md"},
            {"root": self.other},
        ]

    def run_retire(self, *args: str, check: bool = True):
        return run_command([
            sys.executable, str(REPO_ROOT / "scripts/retire-agent-clients.py"),
            "--home", str(self.home), "--repo-registry", str(self.registry), *args,
        ], check=check)

    def retirement(self):
        return RETIRE.Retirement(self.home, self.github, self.entries)

    def hook(self, script: str = "claude_stop.py", runtime: str = "") -> dict:
        return {"type": "command", "command": f'python3 "$HOME/GitHub/agents/hooks/scripts/{script}"{runtime}'}

    def link(self, path: Path, target: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.symlink_to(os.path.relpath(target, path.parent))
        return path

    def test_dry_run_and_check_do_not_write_or_reveal_config_values(self) -> None:
        target = write_json(self.home / ".copilot/settings.json", {"askUser": False, "token": "KEEP_PRIVATE_TOKEN"})
        before = target.read_bytes()
        dry = self.run_retire()
        self.assertEqual(dry.returncode, 0)
        self.assertIn("UPDATE", dry.stdout)
        self.assertNotIn("KEEP_PRIVATE_TOKEN", dry.stdout + dry.stderr)
        checked = self.run_retire("--check", check=False)
        self.assertEqual(checked.returncode, 1)
        self.assertEqual(target.read_bytes(), before)
        self.assertFalse((self.home / ".local/state").exists())

    def test_repo_cleanup_preserves_codex_identity_workflows_and_real_skills(self) -> None:
        identity = write_text(self.repo / "identity.md", "private identity source\n")
